/**
 * ============================================================================
 * BLOG STORE, server-only. Reads the repo's Markdown files and, when Vercel
 * Blob is configured, every post published from /studio. Blob wins on slug
 * collisions, so you can always correct a seed post without a redeploy.
 * ============================================================================
 * With BLOB_READ_WRITE_TOKEN set, an edit in /studio appears within seconds.
 * Without it, the site runs on `content/blog/*.md` alone, the studio tells you
 * exactly what to set. Nothing here throws; a failed read degrades to files.
 * ============================================================================
 */

import "server-only";
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";
import { list } from "@vercel/blob";
import { buildPost, parseMarkdown } from "../markdown";
import { publicPosts, type Post } from "../blog";
import snapshot from "../blog.snapshot.json";

const DIR = path.join(process.cwd(), "content", "blog");
const PREFIX = "posts/";
const hasBlob = Boolean(process.env.BLOB_READ_WRITE_TOKEN);

type DiskPost = { slug: string; name: string; text: string };

function readFiles(): DiskPost[] {
  try {
    return fs
      .readdirSync(DIR)
      .filter((f) => f.endsWith(".md") || f.endsWith(".mdx"))
      .map((f) => ({
        slug: f.replace(/\.mdx?$/, ""),
        name: f,
        text: fs.readFileSync(path.join(DIR, f), "utf8"),
      }));
  } catch {
    return [];
  }
}

/** Parsed posts from the repo, drafts included, memoised per build/process. */
let fileCache: Post[] | null = null;

/**
 * Posts from `content/blog`. If the Markdown can't be read at runtime (some
 * serverless bundles do not include it), fall back to the committed snapshot
 * generated by `npm run sync:blog`, same posts, already parsed.
 */
function filePosts(): Post[] {
  if (fileCache) return fileCache;

  const files = readFiles();
  if (!files.length) {
    fileCache = (snapshot.posts as unknown as Post[]).map((p) => ({ ...p }));
    return fileCache;
  }

  const out: Post[] = [];
  for (const f of files) {
    const { data, content } = matter(f.text);
    const post = buildPost(f.slug, data as Record<string, unknown>, content);
    if (post) out.push(post);
  }
  fileCache = out;
  return out;
}

type BlobRecord = {
  slug: string;
  title: string;
  excerpt: string;
  date: string;
  updated?: string;
  tags: string[];
  draft?: boolean;
  cover?: string;
  markdown: string;
};

/** Every blob at posts/*.md, newest first. Never throws. */
async function blobRecords(): Promise<BlobRecord[]> {
  if (!hasBlob) return [];
  try {
    const { blobs } = await list({ prefix: PREFIX, limit: 1000 });
    const files = blobs.filter((b) => b.pathname.endsWith(".md"));
    const out: BlobRecord[] = [];
    await Promise.all(
      files.map(async (b) => {
        try {
          const res = await fetch(b.url, { next: { revalidate: 60 } });
          if (!res.ok) return;
          const { data, content } = matter(await res.text());
          const post = buildPost(
            b.pathname.replace(PREFIX, "").replace(/\.md$/, ""),
            data as Record<string, unknown>,
            content,
          );
          if (!post) return;
          out.push({
            slug: post.slug,
            title: post.title,
            excerpt: post.excerpt,
            date: post.date,
            updated: post.updated,
            tags: post.tags,
            draft: post.draft,
            cover: post.cover,
            markdown: content,
          });
        } catch {
          /* one bad file must never take the blog down */
        }
      }),
    );
    return out;
  } catch {
    return [];
  }
}

/** Merge: a blob post replaces a file post with the same slug. */
function merge(files: Post[], records: BlobRecord[]): Post[] {
  const bySlug = new Map(files.map((p) => [p.slug, p]));
  for (const r of records) {
    bySlug.set(r.slug, {
      slug: r.slug,
      title: r.title,
      excerpt: r.excerpt,
      date: r.date,
      updated: r.updated,
      tags: r.tags,
      featured: false,
      draft: r.draft,
      cover: r.cover,
      content: parseMarkdown(r.markdown),
      readMinutes: buildPost(r.slug, { title: r.title, date: r.date }, r.markdown)?.readMinutes ?? 1,
    });
  }
  return [...bySlug.values()];
}

/** Everything, drafts included, for /studio. */
export async function allPosts(): Promise<Post[]> {
  return merge(filePosts(), await blobRecords()).sort((a, b) => b.date.localeCompare(a.date));
}

/** What the public site sees: published only, newest first. */
export async function publishedPosts(): Promise<Post[]> {
  return publicPosts(await allPosts());
}

export async function findPost(slug: string): Promise<Post | undefined> {
  const all = await allPosts();
  return all.find((p) => p.slug === slug && !p.draft);
}

/** Raw Markdown for the studio editor, plus whether it came from a blob. */
export async function rawPost(
  slug: string,
): Promise<{ markdown: string; source: "blob" | "file" } | null> {
  const records = await blobRecords();
  const record = records.find((r) => r.slug === slug);
  if (record) return { markdown: record.markdown, source: "blob" };
  const file = readFiles().find((f) => f.slug === slug);
  if (file) return { markdown: matter(file.text).content.trim(), source: "file" };

  // Last resort: the snapshot. Blocks are rebuilt into Markdown-ish text only
  // where possible, so the editor shows the body rather than nothing.
  const snap = (snapshot.posts as unknown as Post[]).find((p) => p.slug === slug);
  if (snap) return { markdown: blocksToMarkdown(snap), source: "file" };
  return null;
}

/** Blocks → Markdown, so the studio can edit a snapshot-only post. */
function blocksToMarkdown(post: Post): string {
  const out: string[] = [];
  for (const b of post.content) {
    switch (b.type) {
      case "heading":
        out.push(`${"#".repeat(b.level)} ${b.text}`);
        break;
      case "paragraph":
        out.push(b.text);
        break;
      case "code":
        out.push("```" + b.lang, b.code, "```");
        break;
      case "callout":
        out.push(`> [!${b.kind.toUpperCase()}]
> ${b.text}`);
        break;
      case "list":
        out.push(b.items.map((i, n) => (b.ordered ? `${n + 1}. ${i}` : `- ${i}`)).join("\n"));
        break;
      case "quote":
        out.push(`> ${b.text}`);
        break;
      case "image":
        out.push(`![${b.alt}](${b.src})` + (b.caption ? `
_${b.caption}_` : ""));
        break;
      case "table":
        out.push(
          `| ${b.head.join(" | ")} |`,
          `| ${b.head.map(() => "---").join(" | ")} |`,
          ...b.rows.map((r) => `| ${r.join(" | ")} |`),
        );
        break;
      case "hr":
        out.push("---");
        break;
    }
    out.push("");
  }
  return out.join("\n").trim();
}

export const blogStore = { hasBlob, prefix: PREFIX };
